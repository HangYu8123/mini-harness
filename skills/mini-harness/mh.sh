# Final usage per sealed record, written beside the record, never into it: the record was sealed
# before its final response existed, so `end` could only stamp a provisional count. Recounts the
# run's interval (start stamp → the next user prompt after the seal) once the transcript has
# settled, at most five records per call. Sets FINALIZED to the number written.
usage_finalize() { local i f name line sess stamp receipt out dir="$H/state/usage"; FINALIZED=0
  i=$(py_interp) || return 0; [ -f "$SKILL_DIR/mh_usage.py" ] || return 0
  for f in "$H"/exec_traj/*.md; do
    [ -f "$f" ] || continue; name=${f##*/}; receipt="$H/state/trajectories/$name.sha256"
    [ -s "$receipt" ] || continue; [ -f "$dir/$name.usage" ] && continue
    line=$(record_field "$f" usage); case "$line" in provisional*) ;; *) continue;; esac
    sess=$(printf '%s' "$line" | sed -n 's/.*session \([0-9A-Za-z-]*\).*/\1/p'); [ -n "$sess" ] || continue
    stamp=$(printf '%s' "$name" | cut -d_ -f1,2)
    out=$("$i" "$SKILL_DIR/mh_usage.py" --repo "$ROOT" --line --since "$stamp" --until-mtime "$receipt" --session "$sess" --settled 2>/dev/null) || continue
    [ -n "$out" ] || continue
    mkdir -p "$dir" || return 0
    printf 'final · %s\n' "$out" > "$dir/$name.usage" || continue
    printf 'usage    final %s → .harness/state/usage/%s.usage\n' "$name" "$name"
    FINALIZED=$((FINALIZED+1)); [ "$FINALIZED" -ge 5 ] && break
  done; return 0; }

