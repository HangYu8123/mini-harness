    if [ "$plat" != "<platform>" ]; then t=$(mktemp); sed "1,2s|· <platform> ·|· $plat ·|" "$f" > "$t" && cat "$t" > "$f"; rm -f "$t"; fi
    printf 'record   %s\n' "$f"
    memory_line
    routes_for "$req" ${1+"$@"}
    if [ $# -gt 0 ]; then for p in "$@"; do out=$(fingerprint_one "$p") || exit $?; printf 'fingerprint %s\n' "$out"; done; fi
    gate_line
    usage_finalize >/dev/null 2>&1 || true      # earlier records' final usage, once their transcripts settled
    exit 0;;
  end)
    # end <filename> [--<line> "<text>"]... — the whole run-end bookkeeping in one call, and the only
    # place an agent line enters the record: fill every line passed (only where a placeholder still
    # stands), write `unknown` into the rest, close `repo state`, stamp a provisional `usage` bound to
    # the run's start stamp, derive the memory lines, and seal. Retry-safe: a sealed record is a
    # no-op, and a memory line already present is never appended twice.
    name=${2:-}
    traj_name_ok "$name" || { echo "mh.sh end: record missing or invalid (pass a trajectory basename)" >&2; exit 2; }
    shift 2
    rec="$H/exec_traj/$name"; task=$(traj_task "$name"); wrote=""; kept=""
    ch=""; fr=""; hc=false; hf=false; keys=""; vals=""
    while [ $# -gt 0 ]; do
      case "$1" in
        --outcome) k=outcome;; --dispositions) k=dispositions;; --changed) k=changed;; --effect) k="harness effect";;
        --friction) k=friction;; --request) k=request;; --native-path) k="native path";; --memory) k="memory consulted";;
        --advisory) k=advisory;; --verification) k=verification;; --choices) k="user choices";;
        *) echo "mh.sh end: unknown argument '$1'" >&2; exit 2;;
      esac
      [ $# -ge 2 ] || { echo "mh.sh end: $1 needs a value" >&2; exit 2; }
      case "$1" in --changed) ch=$2; hc=true;; --friction) fr=$2; hf=true;; esac
      keys="$keys$k"$'\n'; vals="$vals$2"$'\n'; shift 2
    done
    # A sealed record is immutable: an unchanged one is already finished, a changed one is a defect.
    receipt="$H/state/trajectories/$name.sha256"
    if [ -s "$receipt" ]; then
      [ "$(cat "$receipt")" = "$(hash_of "$rec")" ] || { echo "mh.sh end: completed record changed; preserve it and record a correction in a new trajectory" >&2; exit 1; }
      echo "sealed   $name (already sealed; nothing written)"; exit 0
    fi
    # The values travel by index through two newline-joined lists (a value may carry any character
    # but a newline, which the record's one-line-per-field shape excludes anyway).
    i=1; while :; do k=$(printf '%s' "$keys" | sed -n "${i}p"); [ -n "$k" ] || break
      v=$(printf '%s' "$vals" | sed -n "${i}p"); set_line "$rec" "$k" "$v" || exit 1; i=$((i+1)); done
    for k in request outcome "native path" "memory consulted" advisory dispositions changed verification "user choices" "harness effect" friction; do
      set_line "$rec" "$k" unknown || exit 1; done
    t=$(mktemp); sed '1{/^<!-- fill from what the run already holds/d;}' "$rec" > "$t" && cat "$t" > "$rec"; rm -f "$t"
    dirty=$(git -C "$ROOT" status --short 2>/dev/null | wc -l | tr -d ' '); head=$(git -C "$ROOT" log -1 --format='%h %ci' 2>/dev/null | cut -c1-24)
    close_repo_state "$rec" "${dirty:-?} dirty files · head ${head:-none} at $(date '+%H:%M')" || exit 1
    # Usage is counted from the user prompt that preceded this record's start stamp, descendants
    # included, and is provisional: the final response has not happened yet. `usage finalize`
    # writes the settled figure beside the record.
    if u=$(usage_oneline "$(printf '%s' "$name" | cut -d_ -f1,2)"); then u="provisional · $u"; else u="unknown — no transcript found"; fi
    set_line "$rec" usage "$u" || exit 1
    # Friction outlives the record: it belongs in repo memory as an observation — the fix it names
    # stays proposed until a later run verifies it (repo_info/README.md, lesson lines).
    if $hf && [ -n "$fr" ] && [ "$fr" != none ] && [ "$fr" != unknown ]; then
      note_target persistent_issues.md "- $(date '+%Y-%m-%d') · $task · observed · scope $(platform_id) $(uname -s 2>/dev/null | cut -d_ -f1) · $fr — evidence: exec_traj/$name · fix: proposed" || exit 1
      if [ "$NOTED_DUP" = 1 ]; then kept="$kept $NOTED"; else wrote="$wrote $NOTED"; fi
    fi
    case "$task" in update|debug|refactor|exec|pr|loop)
      if $hc && [ -n "$ch" ] && [ "$ch" != unknown ]; then
        note_target update_logs.md "- $(date '+%Y-%m-%d') · $task · $(record_field "$rec" request) · $ch" || exit 1
        if [ "$NOTED_DUP" = 1 ]; then kept="$kept $NOTED"; else wrote="$wrote $NOTED"; fi
      fi;;
    esac
    traj_seal "$name" || exit 1
    echo "sealed   $name"
    for m in $wrote; do printf 'noted    %s\n' "$m"; done
    for m in $kept; do printf 'kept     %s (line already present)\n' "$m"; done
    exit 0;;
  usage)
    # usage [--json] [--all] [--limit n] [--rates file] [--compare on.json off.json] | usage finalize —
    # what this repo's Claude Code sessions cost, read from the transcripts the platform already
    # writes; `finalize` settles the provisional usage of sealed records into state/usage/.
    shift
    if [ "${1:-}" = finalize ]; then usage_finalize; echo "usage    finalized $FINALIZED record(s)"; exit 0; fi
    interp=$(py_interp) || { echo "mh.sh usage: needs Python 3.8+ on PATH (py | python3 | python)" >&2; exit 1; }
    [ -f "$SKILL_DIR/mh_usage.py" ] || { echo "mh.sh usage: $SKILL_DIR/mh_usage.py is missing — reinstall the pack" >&2; exit 1; }
    exec "$interp" "$SKILL_DIR/mh_usage.py" --repo "$ROOT" "$@";;
  routes)
    shift; [ $# -gt 0 ] || { echo "usage: mh.sh routes <word or path> ..." >&2; exit 2; }
    [ -s "$H/repo_info/routes.md" ] || { echo "routes   none — repo_info/routes.md is empty (mh-init builds it; note routes.md adds one)"; exit 0; }
    out=$(MH_ROUTE_MAX=12 MH_ROUTE_ANY=1 routes_for "$@")
    if [ -n "$out" ]; then printf '%s\n' "$out"; else echo "routes   no match — try other words, or the repo_info/README.md rows"; fi
    exit 0;;
  fingerprint)
    shift; [ $# -gt 0 ] || { echo "usage: mh.sh fingerprint <repo-relative file> ..." >&2; exit 2; }
    for p in "$@"; do
      case "$p" in ''|/*|*\\*|..|../*|*/../*|*/..|*:*) echo "mh.sh fingerprint: expected repo-relative file: $p" >&2; exit 2;; esac
      if [ -f "$ROOT/$p" ]; then digest=$(hash_of "$ROOT/$p") || exit 1; printf '%s  %s\n' "$digest" "$p"
      elif [ -e "$ROOT/$p" ] || [ -L "$ROOT/$p" ]; then echo "mh.sh fingerprint: not a readable regular file: $p" >&2; exit 2
      else printf 'missing  %s\n' "$p"; fi
    done; exit 0;;
  *) echo "usage: mh.sh on | off | status | doctor | begin <task> [--request \"<text>\"] [files...] | end <filename> [--outcome|--changed|--effect|--friction|--dispositions|--native-path|--memory|--advisory|--verification|--choices|--request \"<text>\"] | usage [--json|--limit N|--all|--rates <file>|--compare <on.json> <off.json>] | usage finalize | traj <task> | traj complete <filename> | note <file|untaken> \"<line>\" | untaken [n] | routes <words...> | fingerprint <files...> | wiki begin | wiki end <owner> | effort <level|keep|reset|save|restore|init-save|init-restore <owner>|init-keep <owner>> [researcher=<level>] [claude-model=<id>] [codex-model=<id>] | subagents [status|on ...|off]" >&2; exit 2;;
esac
