# ---------------------------------------------------------------- run bookkeeping (begin / end)
# One call at each boundary. `begin` reserves and stamps the record and hands back what the run
# needs anyway (what repo memory holds, fingerprints, the gate rule); `end` fills
# the mechanical lines, derives the memory lines, and seals. Both reuse `traj`'s code.
platform_id() {   # the record's <platform> field, read from the environment the run is in
  if [ -n "${CLAUDE_PROJECT_DIR:-}${CLAUDE_PLUGIN_ROOT:-}${CLAUDECODE:-}" ]; then printf 'claude-code'
  elif [ -n "${CODEX_HOME:-}${CODEX_SANDBOX:-}" ]; then printf 'codex'
  else printf '<platform>'; fi; }
# Worker pins as the definitions carry them at run start: the dominant <model>/<effort> per
# platform, then every role that differs. Definition evidence, not launch evidence.
pins_for() { local kind=$1 dir=$2 f role list=""
  for f in "$dir"/*; do
    [ -f "$f" ] && [ ! -L "$f" ] && grep -q "$MARKER" "$f" || continue
    case "$kind:$f" in
      claude:*.md) role=${f##*/}; role=${role%.md}
        list="$list$role $(claude_val "$f" model)/$(claude_val "$f" effort)
";;
      codex:*.toml) role=${f##*/}; role=${role%.toml}
        list="$list$role $(codex_val "$f" model)/$(codex_val "$f" model_reasoning_effort)
";;
      *) continue;;
    esac
  done
  [ -n "$list" ] || return 1
  printf '%s' "$list" | awk '{r[NR]=$1; pin[NR]=$2; c[$2]++} END{
    best=""; bn=0; for (k in c) if (c[k]>bn || (c[k]==bn && k<best)) { best=k; bn=c[k] }
    out=best; for (i=1;i<=NR;i++) if (pin[i]!=best) out=out" except "r[i]" "pin[i]; printf "%s", out}'; }
worker_pins() { local out="" part
  part=$(pins_for claude "$ROOT/.claude/agents") && out="claude $part"
  part=$(pins_for codex "$ROOT/.codex/agents") && out="${out:+$out · }codex $part"
  printf '%s' "${out:-none found}"; }
line_count() { [ -s "$1" ] && awk 'END{print NR}' "$1" || printf 0; }
# What repo memory holds right now, so a file is read only when this line says it is worth it.
memory_line() { local r="$H/repo_info" pref ov
  pref=$(awk '{sub(/\r$/,"")} NF{ if (n++) printf "; "; printf "%s", $0 } END{ if (!n) printf "empty" }' "$r/preference.md" 2>/dev/null)
  [ -n "$pref" ] || pref=empty
  if [ -s "$r/codebase_overview.md" ] || [ -s "$r/scripts_overview.md" ]; then ov=present; else ov=empty; fi
  printf 'memory   .harness/repo_info/ (README.md indexes it) · preference.md: %s · known_issues %s lines · persistent_issues %s · past_QA %s · update_logs %s · overviews %s\n' \
    "$pref" "$(line_count "$r/known_issues.md")" "$(line_count "$r/persistent_issues.md")" \
    "$(line_count "$r/past_QA.md")" "$(line_count "$r/update_logs.md")" "$ov"; }
# The gate rule (harness.md §5), where it is cheap to read: advisors only on a hook signal.
gate_line() { printf 'gate     advisors only on a [mini-harness gate] signal line the hook injected this request, or an on-dial; no signal, no advisor. prompt: version → look it up yourself · research → online-researcher · alternatives → diversifier. tool drift: 1st → look up the pinned version yourself · 2nd → online-researcher · 3rd → devils-advocate. Pass what fired, or "none fired", in --advisory at end\n'; }
# Task-oriented routes (repo_info/routes.md): the lines whose symptom/domain head carries a request
# word (5+ letters, common words dropped), or that name one of the files the run depends on — at
# most MH_ROUTE_MAX (5). A route names the entry file directly, so it is read before any overview.
# `routes <words>` sets MH_ROUTE_ANY=1: deliberate words, 3+ letters, matched anywhere in the line.
routes_for() { local r="$H/repo_info/routes.md"
  [ -s "$r" ] || return 0
  MH_Q="$*" MH_MAX="${MH_ROUTE_MAX:-5}" MH_ANY="${MH_ROUTE_ANY:-0}" awk '
    BEGIN{ n=split(tolower(ENVIRON["MH_Q"]), w, /[^a-z0-9_.\/-]+/); k=0; any=ENVIRON["MH_ANY"]+0; min=any?3:5
      m=split("about after again before being could every first other should their there these those through which while without would please using change changes update fixes", sw, " ")
      for (i=1;i<=m;i++) stop[sw[i]]=1
      for (i=1;i<=n;i++) { if (w[i] ~ /[\/.]/) { if (length(w[i])>=3) keys[++k]=w[i] } else if (length(w[i])>=min && (any || !(w[i] in stop))) keys[++k]=w[i] } }
    k>0 && /^- / { l=tolower($0); h=l; i=index(l," → "); if (i && !any) h=substr(l,1,i)
      for (j=1;j<=k;j++) if ((keys[j] ~ /[\/.]/ && index(l,keys[j])) || index(h,keys[j])) { print "route    " $0; if (++c>=ENVIRON["MH_MAX"]+0) exit; break } }' "$r"; }
fingerprint_one() { local p=$1 digest
  case "$p" in ''|/*|*\\*|..|../*|*/../*|*/..|*:*) echo "mh.sh fingerprint: expected repo-relative file: $p" >&2; return 2;; esac
  if [ -f "$ROOT/$p" ]; then digest=$(hash_of "$ROOT/$p") || return 1; printf '%s  %s\n' "$digest" "$p"
  elif [ -e "$ROOT/$p" ] || [ -L "$ROOT/$p" ]; then echo "mh.sh fingerprint: not a readable regular file: $p" >&2; return 2
  else printf 'missing  %s\n' "$p"; fi; }
# Line values carry ·, quotes, &, | and / — they travel through the environment, never through a
# sed replacement (a `sonnet/medium` once collided with the s/// delimiter).
set_line() { local f=$1 t rc; t=$(mktemp) || return 1
  MH_KEY=$2 MH_VAL=$3 awk '
    BEGIN{ k=ENVIRON["MH_KEY"]; v=ENVIRON["MH_VAL"]; n=length(k)+1; done=0 }
    !done && substr($0,1,n)==k":" {
      rest=substr($0,n+1); sub(/\r$/,"",rest); sub(/^[ \t]*/,"",rest)
      # only a placeholder or an empty line is filled; a line the agent wrote by hand stays
      if (rest=="" || rest ~ /<[^>]*>/) { print k": " v; done=1; next } }
    {print}' "$f" > "$t" && cat "$t" > "$f"; rc=$?; rm -f "$t"; return "$rc"; }
close_repo_state() { local f=$1 t rc; t=$(mktemp) || return 1
  MH_VAL=$2 awk 'BEGIN{ v=ENVIRON["MH_VAL"]; done=0 }
    !done && /^repo state:/ && index($0, " → ")==0 { line=$0; sub(/\r$/,"",line); print line" → "v; done=1; next }
    {print}' "$f" > "$t" && cat "$t" > "$f"; rc=$?; rm -f "$t"; return "$rc"; }
