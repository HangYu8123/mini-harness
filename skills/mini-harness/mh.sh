  else ( set -C; printf '%s\n' "$digest" > "$receipt" ) || return 1; fi; return 0; }
# One line into repo memory without the agent reading the file first (each read lands in the main
# context for the rest of the session). update_logs.md is newest-first, so it is prepended; the
# others are appended. Sets NOTED to the file; a line already present is never written twice
# (NOTED_DUP=1), so a retried `end` cannot duplicate friction or an update-log line.
note_target() { local f=$1 line=$2 p t
  mkdir -p "$H/repo_info" || return 1; NOTED_DUP=0
  case "$f" in
    update_logs.md|preference.md|routes.md|known_issues.md|persistent_issues.md|past_QA.md) p="$H/repo_info/$f";;
    untaken) p="$H/repo_info/known_issues.md";;
    *) echo "mh.sh note: unknown target '$f'" >&2; return 2;;
  esac
  [ -f "$p" ] && grep -qxF -- "$line" "$p" && { NOTED=$p; NOTED_DUP=1; return 0; }
  case "$f" in
    update_logs.md) [ -f "$p" ] || : > "$p"
      t=$(mktemp); { printf '%s\n' "$line"; cat "$p"; } > "$t" && cat "$t" > "$p"; rm -f "$t";;
    untaken) [ -f "$p" ] || : > "$p"
      if grep -q '^## Untaken options' "$p"; then t=$(mktemp)
        awk -v l="$line" 'BEGIN{s=0;b=""} /^## Untaken options/{s=1; print; next}
          s==1 && /^$/ {b=b"\n"; next}                       # hold the section'"'"'s trailing blank lines
          s==1 && /^## /{print l; printf "%s", b; s=2; b=""}  # new line goes last in the section, blanks after it
          s==1 {printf "%s", b; b=""} {print} END{if(s==1) print l}' "$p" > "$t" && cat "$t" > "$p"; rm -f "$t"
      else printf '\n## Untaken options\n%s\n' "$line" >> "$p"; fi;;
    *) printf '%s\n' "$line" >> "$p";;
  esac; NOTED=$p; return 0; }
# Shell cannot parse JSONL usefully, so the one subcommand that reads transcripts delegates to
# mh_usage.py; every other subcommand stays pure shell. `py` first: on Windows `python3`/`python`
# are Store stubs that sit on PATH and do nothing, so every candidate is probed by running it.
py_interp() { local c; for c in py python3 python; do "$c" -c "import sys" >/dev/null 2>&1 && { printf '%s' "$c"; return 0; }; done; return 1; }
usage_oneline() { local i out stamp=${1:-}
